import React from 'react';
import { Document, Page, View, Text } from '@react-pdf/renderer';
import { accountTypeDetail } from '../../utils/ledgerLabels.js';
import type {
  CashBankAccountRow,
  CashBankFigures,
  CashBankGroupSummary,
  CashBankSummary,
} from '../../components/reports/cash-bank/cashBankSummary.js';
import {
  C,
  LetterheadBand,
  s,
  TableView,
  inr,
  type Cell,
  type Col,
  type Letterhead,
} from './shiftSummaryDoc.js';
import { generatedLabel } from './ledgerDoc.js';
import {
  CASH_BANK_TOTAL_LABEL,
  groupTotalLabel,
} from '../../components/reports/cash-bank/labels.js';

export interface CashBankDocProps {
  summary: CashBankSummary;
  periodLabel: string;
  stationName?: string;
  letterhead?: Letterhead;
  showLogo?: boolean;
  generatedAt?: string;
  paper?: 'A4' | 'LETTER';
}

const COLS: Col[] = [
  { header: 'Account', flex: 2.6, strong: true },
  { header: 'Opening', flex: 1.3, align: 'right', mono: true },
  { header: 'In', flex: 1.3, align: 'right', mono: true },
  { header: 'Out', flex: 1.3, align: 'right', mono: true },
  { header: 'Closing', flex: 1.3, align: 'right', mono: true, strong: true },
];

const figures = (f: CashBankFigures): Cell[] => [
  { text: inr(f.opening) },
  { text: inr(f.moneyIn) },
  { text: inr(f.moneyOut) },
  { text: inr(f.closing), color: f.closing < 0 ? C.danger : C.ink },
];

const accountRow = (a: CashBankAccountRow): Cell[] => [
  { text: a.accountName, detail: accountTypeDetail(a.accountName, a.accountType) ?? undefined },
  ...figures(a),
];

/** The cells the PDF prints, group by group (exported for a parity test). */
export function cashBankDocTables(summary: CashBankSummary) {
  const group = (name: string, g: CashBankGroupSummary) => ({
    title: name.toUpperCase(),
    rows: g.shown.map(accountRow),
    total: [{ text: groupTotalLabel(g) }, ...figures(g.totals)] as Cell[],
  });
  return {
    groups: [group('Cash', summary.cash), group('Bank', summary.bank)],
    total: [{ text: CASH_BANK_TOTAL_LABEL }, ...figures(summary.total)] as Cell[],
    other: summary.other.shown.length > 0 ? group('Other accounts', summary.other) : null,
  };
}

/**
 * Reports › Cash & bank as a PDF (#531): the summary table, the same rows and
 * totals the screen shows. Each account's statement prints from its own view
 * on Accounts.
 */
export const CashBankDoc: React.FC<CashBankDocProps> = ({
  summary,
  periodLabel,
  stationName,
  letterhead,
  showLogo = true,
  generatedAt,
  paper = 'A4',
}) => {
  const { groups, total, other } = cashBankDocTables(summary);
  return (
    <Document>
      <Page size={paper} style={s.page}>
        <LetterheadBand
          title="CASH & BANK SUMMARY"
          stationName={stationName}
          letterhead={letterhead}
          showLogo={showLogo}
        />
        <Text style={s.sub}>
          {periodLabel}
          {generatedAt ? ` \u2022 Generated ${generatedLabel(generatedAt)}` : ''}
        </Text>
        {groups.map((g, i) => (
          <View key={g.title}>
            <Text style={s.h2}>{g.title}</Text>
            {/* The Cash + Bank line closes the Bank table, right under its total. */}
            <TableView
              columns={COLS}
              rows={g.rows}
              total={g.total}
              totals={i === groups.length - 1 ? [total] : undefined}
            />
          </View>
        ))}
        {other && (
          <View>
            <Text style={s.h2}>OTHER ACCOUNTS (NOT IN CASH + BANK)</Text>
            <TableView columns={COLS} rows={other.rows} total={other.total} />
          </View>
        )}
        <View style={s.foot} fixed>
          <Text>Generated by PumpOS</Text>
          <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} / ${totalPages}`} />
        </View>
      </Page>
    </Document>
  );
};
